import assert from 'node:assert/strict';
import { criarCoop } from './coop.mjs';
const mensagens=new Map();
const coop=criarCoop((j,m)=>mensagens.set(j.id,m));
const a={id:'a'}, b={id:'b'}, c={id:'c'}, d={id:'d'};
const contexto={campanha:'campanha_primeira_raiz_v1',regiao:'chegada'};
coop.aoMensagem(a,{t:'coop_criar',...contexto,perfil:{apelido:'ANA'}});
const sala=mensagens.get('a');
assert.equal(sala.regiao,'chegada');
coop.aoMensagem(c,{t:'coop_criar',...contexto,regiao:'pomar',perfil:{apelido:'CAIO'}});
coop.aoMensagem(d,{t:'coop_listar',...contexto});
assert.deepEqual(mensagens.get('d').salas.map(s=>s.codigo),[sala.codigo]);
coop.aoMensagem(d,{t:'coop_listar'});
assert.deepEqual(mensagens.get('d').salas,[],'arena não recebe salas da campanha');
coop.aoMensagem(b,{t:'coop_entrar',codigo:sala.codigo,perfil:{}});
assert.equal(mensagens.get('b').erro,'contexto_invalido');
coop.aoMensagem(b,{t:'coop_entrar',...contexto,regiao:'pomar',codigo:sala.codigo,perfil:{}});
assert.equal(mensagens.get('b').erro,'contexto_invalido');
coop.aoMensagem(b,{t:'coop_entrar',...contexto,codigo:sala.codigo,perfil:{}});
assert.equal(mensagens.get('b').jogadores.length,2);
coop.aoMensagem(d,{t:'coop_criar',...contexto,regiao:'inexistente',perfil:{}});
assert.equal(mensagens.get('d').erro,'contexto_invalido');
coop.aoMensagem(a,{t:'coop_iniciar'});
coop.aoMensagem(d,{t:'coop_entrar',...contexto,codigo:sala.codigo,perfil:{}});
assert.equal(mensagens.get('d').erro,'em_partida');
coop.sair(a,true);
assert.equal(mensagens.get('b').t,'coop_fim');
coop.aoMensagem(d,{t:'coop_listar',...contexto});
assert.deepEqual(mensagens.get('d').salas,[]);
console.log('OK salas por estágio, isolamento da arena, contexto, lotação de partida e saída');
